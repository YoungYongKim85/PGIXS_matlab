% ========================================================================
% Structure_Callback
    function Structure_Callback(~,~)
        param.Xtal = XTal.CrystalSystem{get(XTal.hCrystsys,'Value')};
        param.Spg = XTal.SpaceGroup{get(XTal.hSpaceGrp,'Value')};
        param.Normal = NormdirecList{get(hNormDirec,'Value')};
        Rotation = parsePGIXSRotationVector({get(hXrot,'String'), get(hYrot,'String'), get(hZrot,'String')});

        switch param.Xtal
            case 'Layer'
                a = inf; b = inf; c = 1;
                alpha = 90; beta = 90; gamma = 90;
            case 'Hexagonal'
                a = 1; b = 1; c = inf;
                alpha = 90; beta = 90; gamma = 120;
            case 'HCP'
                a = 1; b = 1; c = 1.633;
                alpha = 90; beta = 90; gamma = 120;
            case 'Cubic'
                a = 1; b = 1; c = 1;
                alpha = 90; beta = 90; gamma = 90;
            case 'Orthorhombic'
                a = 1; b = 2; c = 3;
                alpha = 90; beta = 90; gamma = 90;
            case 'Tetragonal'
                a = 1; b = 1; c = 2;
                alpha = 90; beta = 90; gamma = 90;
            case 'Monoclinic'
                a = 1; b = 2; c = 3;
                alpha = 90; beta = 70; gamma = 90;
            case 'Rhombohedral'
                a = 1; b = 1; c = 1;
                alpha = 70; beta = 70; gamma = 70;
            case 'Triclinic'
                a = 1; b = 2; c = 3;
                alpha = 70; beta = 80; gamma = 100;
        end
        GX.haunit.String = num2str(a);
        GX.hbunit.String = num2str(b);
        GX.hcunit.String = num2str(c);
        GX.halpha.String = num2str(alpha);
        GX.hbeta.String = num2str(beta);
        GX.hgamma.String = num2str(gamma);
        cla(hImunit);
        axes(hImunit);

        UnitCellGen_gixs(a,b,c,alpha,beta,gamma,param.Xtal,param.Spg,param.Normal,Rotation);
    end

