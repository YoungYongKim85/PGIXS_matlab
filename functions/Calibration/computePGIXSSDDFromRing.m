function [sdd, report] = computePGIXSSDDFromRing(pixelRadius, pixelSize, energyKeV, qValue)
% computePGIXSSDDFromRing  Compute sample-detector distance from one ring.

    validateattributes(pixelRadius, {'numeric'}, {'scalar', 'positive', 'finite'}, ...
        mfilename, 'pixelRadius');
    validateattributes(pixelSize, {'numeric'}, {'scalar', 'positive', 'finite'}, ...
        mfilename, 'pixelSize');
    validateattributes(energyKeV, {'numeric'}, {'scalar', 'positive', 'finite'}, ...
        mfilename, 'energyKeV');
    validateattributes(qValue, {'numeric'}, {'scalar', 'positive', 'finite'}, ...
        mfilename, 'qValue');

    hConst = 4.1357e-15;
    cConst = 2.99792458e8;
    wavelength = hConst * cConst / (double(energyKeV) * 1e3) * 1e10;
    sinTheta = wavelength * double(qValue) / (4 * pi);
    if sinTheta <= 0 || sinTheta >= 1
        error('PGIXS:InvalidSDDGeometry', ...
            'Invalid q/energy combination for SDD calculation.');
    end

    twoThetaDeg = 2 * asind(sinTheta);
    sdd = double(pixelRadius) * double(pixelSize) / tand(twoThetaDeg);
    report = struct( ...
        'Wavelength', wavelength, ...
        'TwoThetaDeg', twoThetaDeg, ...
        'PixelRadius', double(pixelRadius), ...
        'PixelSize', double(pixelSize), ...
        'EnergyKeV', double(energyKeV), ...
        'QValue', double(qValue));
end
