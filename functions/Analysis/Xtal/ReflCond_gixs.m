                                (nnz(hkl)==1 && (mod(sum(hkl),4) ==0)) || ...
                                (nnz(hkl)==3 && (numel(unique(hkl))<=2 && mod(2*dupvalue(hkl)+removedup(hkl),4)==0))

                            RC(n) = 1;
                        end
                    end
                end
        end
