function out = removedup(in)
[a,b,~] = unique(in);
if length(b) < 3
    if length(b) == 2
        for ii = 1:2
            ch = find(in == a(ii));
            if isscalar(ch)
                out = in(ch);
            else
                continue
            end
        end
    elseif isscalar(b)
        out = in(1);
    end
else
    out = in(1);
end
end

function out = dupvalue(in)
[a,b,~] = unique(in);
if length(b) < 3
    if length(b) == 2
        for ii = 1:2
            ch = find(in == a(ii));
            if length(ch) == 2
                out = in(ch(1));
            else
                continue
            end
        end
    elseif isscalar(b)
        out = in(1);
    end
else
    out = in(1);
end
end
